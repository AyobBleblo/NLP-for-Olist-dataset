"""
store/ml/loader.py — Singleton loaders for all ML models.

DESIGN PRINCIPLE
================
All heavyweight model loading is isolated here.  Nothing in views.py,
serializers.py, or signals.py may import torch/transformers directly.

Each public getter follows the same pattern:
  - A module-level variable holds the singleton (None until first call).
  - get_X() initialises it on first call, then returns the cached instance.
  - Thread-safety note: Django dev server is single-threaded; for
    production (Gunicorn/uvicorn) use --preload or a dedicated worker
    initializer — the lazy approach is safe enough for the batch commands
    that call these functions.

MODELS MANAGED HERE
===================
1. SentimentPredictor  — binary DistilBERT (Negative / Positive)
   Path: settings.SENTIMENT_MODEL_DIR (models/best_model_binary/)
   Source: inference.SentimentPredictor (already in the project root)

2. Translation pipeline — facebook/nllb-200-distilled-600M
   Same model + tokenizer used in translate_reviews.py.
   Produces: Brazilian Portuguese → English translations.
"""

from __future__ import annotations

import logging
import os
import pickle
from typing import TYPE_CHECKING

import torch
from django.conf import settings

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Collaborative Filtering (SVD) model singleton
# ---------------------------------------------------------------------------

_cf_model = None


def get_cf_model():
    """
    Return the cached Collaborative Filtering model (surprise.SVD),
    loading it from settings.CF_MODEL_PATH on first call.
    Returns None if the file does not exist yet.
    """
    global _cf_model
    if _cf_model is None:
        model_path = getattr(settings, "CF_MODEL_PATH", "")
        if model_path and os.path.exists(model_path):
            try:
                logger.info("Loading Collaborative Filtering SVD model from %s", model_path)
                with open(model_path, "rb") as f:
                    _cf_model = pickle.load(f)
                logger.info("Collaborative Filtering SVD model loaded successfully.")
            except Exception as exc:
                logger.error("Failed to load CF model from %s: %s", model_path, exc)
                _cf_model = None
        else:
            logger.info("CF model file not found at %s (will use popularity fallback)", model_path)
    return _cf_model


# ---------------------------------------------------------------------------
# Content-Based Filtering (TF-IDF + numeric) model singleton
# ---------------------------------------------------------------------------

_cbf_model = None  # dict with keys: tfidf_matrix, num_matrix, pid_to_idx, idx_to_pid, text_weight


def get_cbf_model():
    """
    Return the cached CBF artifacts as a dict, loading on first call from:
      models/processed/cbf_precomputed.npz

    This file is generated by running:
        python precompute_cbf.py   (uses Anaconda / system Python)

    It contains all CBF matrices in plain NumPy format — no pandas, no
    scipy, no sklearn — so it loads cleanly inside the uv venv even when
    Windows Application Control blocks .venv C-extension DLLs.

    Returns a dict with keys:
        tfidf_matrix : np.ndarray  shape (n_products, vocab)   float32
        num_matrix   : np.ndarray  shape (n_products, 5)       float32  log1p+z-score
        pid_to_idx   : dict[str, int]   external_product_id -> row index
        idx_to_pid   : np.ndarray       row index -> external_product_id
        text_weight  : float            CB_TEXT_WEIGHT (0.7 default)

    Returns None if the file is missing (category-affinity fallback is used).
    """
    global _cbf_model
    if _cbf_model is not None:
        return _cbf_model

    precomputed_path = getattr(
        settings, "CBF_PRECOMPUTED_PATH",
        os.path.join(
            os.path.dirname(getattr(settings, "CF_MODEL_PATH", "models/svd_cf.pkl")),
            "processed", "cbf_precomputed.npz",
        ),
    )

    if not os.path.exists(precomputed_path):
        logger.warning(
            "CBF precomputed file not found at %s. "
            "Run: python precompute_cbf.py (system/Anaconda Python). "
            "Category-affinity fallback is active.",
            precomputed_path,
        )
        return None

    try:
        import numpy as np

        logger.info("Loading CBF precomputed artifacts from %s", precomputed_path)
        data = np.load(precomputed_path, allow_pickle=False)

        # Reconstruct sparse TF-IDF matrix as a dense float32 array
        # (vocab is only 193 columns — fits comfortably in RAM as dense)
        tfidf_data    = data["tfidf_data"]
        tfidf_indices = data["tfidf_indices"]
        tfidf_indptr  = data["tfidf_indptr"]
        tfidf_shape   = tuple(data["tfidf_shape"])

        # Reconstruct CSR and convert to dense (193 vocab cols, fine in RAM)
        import scipy.sparse as sp_  # noqa: F401 — already works in uv env
        tfidf_csr = sp_.csr_matrix(
            (tfidf_data, tfidf_indices, tfidf_indptr), shape=tfidf_shape
        )

        num_matrix  = data["num_matrix"].astype(np.float32)
        product_ids = data["product_ids"]
        text_weight = float(data["text_weight"][0])

        pid_to_idx = {pid: i for i, pid in enumerate(product_ids)}
        idx_to_pid = product_ids

        _cbf_model = {
            "tfidf_matrix": tfidf_csr,
            "num_matrix":   num_matrix,
            "pid_to_idx":   pid_to_idx,
            "idx_to_pid":   idx_to_pid,
            "text_weight":  text_weight,
        }
        logger.info(
            "CBF model loaded: %d products, TF-IDF shape %s, text_weight=%.2f",
            len(pid_to_idx), tfidf_csr.shape, text_weight,
        )
        return _cbf_model

    except Exception as exc:
        logger.error("Failed to load CBF precomputed file: %s", exc)
        return None


